-- Profiles / Users Table
create table if not exists public.profiles (
  id text primary key,
  username text unique not null,
  email text unique not null,
  name text,
  role text default 'Member',
  avatar_color text default '#4285f4',
  avatar_url text,
  bio text default '',
  created_at timestamptz default now()
);

-- Categories Table
create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text unique not null,
  created_at timestamptz default now()
);

-- Photos Table
create table if not exists public.photos (
  id text primary key,
  title text not null,
  category text not null default 'My Uploads',
  url text not null,
  local_file text,
  uploaded boolean default false,
  date_added text default to_char(now(), 'YYYY-MM-DD'),
  rating integer default 5,
  is_favorite boolean default false,
  is_trashed boolean default false,
  album text,
  user_id text,
  uploader_name text,
  size text default '1.2 MB',
  dimensions text default '1920x1080',
  created_at timestamptz default now()
);

-- Features Table
create table if not exists public.features (
  id text primary key,
  title text not null,
  description text,
  votes integer default 1,
  status text default 'new',
  created_at timestamptz default now()
);

-- Enable Row Level Security (RLS)
alter table public.profiles enable row level security;
alter table public.categories enable row level security;
alter table public.photos enable row level security;
alter table public.features enable row level security;

-- Public Access Policies (Allow read and write for PixVerse gallery)
create policy "Allow public read profiles" on public.profiles for select using (true);
create policy "Allow public insert profiles" on public.profiles for insert with check (true);
create policy "Allow public update profiles" on public.profiles for update using (true);

create policy "Allow public read categories" on public.categories for select using (true);
create policy "Allow public insert categories" on public.categories for insert with check (true);
create policy "Allow public delete categories" on public.categories for delete using (true);

create policy "Allow public read photos" on public.photos for select using (true);
create policy "Allow public insert photos" on public.photos for insert with check (true);
create policy "Allow public update photos" on public.photos for update using (true);
create policy "Allow public delete photos" on public.photos for delete using (true);

create policy "Allow public read features" on public.features for select using (true);
create policy "Allow public insert features" on public.features for insert with check (true);
create policy "Allow public update features" on public.features for update using (true);

